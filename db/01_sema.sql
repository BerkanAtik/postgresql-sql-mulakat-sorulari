-- E-ticaret örnek veritabanı: şema
--
-- Tablo ve kolon adlarında bilerek Türkçe karakter kullanmadım (musteriler, siparisler...).
-- Böylece sorgu yazarken tırnak işareti gerekmiyor.
--
-- Not: PostgreSQL, foreign key kolonlarına otomatik index açmaz.
-- siparisler.musteri_id gibi kolonlarda index yok; index modülünde bunu kendimiz ekleyeceğiz.

SET client_min_messages = warning;   -- DROP ... IF EXISTS satırları ekrana uyarı basmasın

DROP TABLE IF EXISTS odemeler          CASCADE;
DROP TABLE IF EXISTS siparis_kalemleri CASCADE;
DROP TABLE IF EXISTS siparisler        CASCADE;
DROP TABLE IF EXISTS urunler           CASCADE;
DROP TABLE IF EXISTS kategoriler       CASCADE;
DROP TABLE IF EXISTS musteriler        CASCADE;
DROP TABLE IF EXISTS calisanlar        CASCADE;

CREATE TABLE kategoriler (
    kategori_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad               TEXT NOT NULL UNIQUE,
    ust_kategori_id  INTEGER REFERENCES kategoriler (kategori_id)
);

CREATE TABLE musteriler (
    musteri_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad            TEXT NOT NULL,
    soyad         TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    sehir         TEXT,
    dogum_tarihi  DATE,
    kayit_tarihi  DATE NOT NULL
);

CREATE TABLE urunler (
    urun_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad           TEXT NOT NULL,
    kategori_id  INTEGER NOT NULL REFERENCES kategoriler (kategori_id),
    fiyat        NUMERIC(10, 2) NOT NULL CHECK (fiyat > 0),
    stok         INTEGER NOT NULL CHECK (stok >= 0),
    aktif        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE siparisler (
    siparis_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    musteri_id      INTEGER NOT NULL REFERENCES musteriler (musteri_id),
    siparis_tarihi  TIMESTAMP NOT NULL,
    durum           TEXT NOT NULL
                    CHECK (durum IN ('beklemede', 'kargoda', 'tamamlandi', 'iptal', 'iade')),
    kupon_kodu      TEXT
);

CREATE TABLE siparis_kalemleri (
    kalem_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id   INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    urun_id      INTEGER NOT NULL REFERENCES urunler (urun_id),
    adet         INTEGER NOT NULL CHECK (adet > 0),
    birim_fiyat  NUMERIC(10, 2) NOT NULL CHECK (birim_fiyat > 0),
    UNIQUE (siparis_id, urun_id)
);

CREATE TABLE odemeler (
    odeme_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id    INTEGER NOT NULL REFERENCES siparisler (siparis_id),
    tutar         NUMERIC(12, 2) NOT NULL CHECK (tutar > 0),
    yontem        TEXT NOT NULL CHECK (yontem IN ('kredi_karti', 'havale', 'kapida_odeme')),
    odeme_tarihi  TIMESTAMP NOT NULL
);

-- Şirketin kendi çalışanları. yonetici_id kendi tablosuna bağlı (self join için).
CREATE TABLE calisanlar (
    calisan_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad                TEXT NOT NULL,
    soyad             TEXT NOT NULL,
    departman         TEXT NOT NULL,
    yonetici_id       INTEGER REFERENCES calisanlar (calisan_id),
    maas              NUMERIC(10, 2) NOT NULL CHECK (maas > 0),
    ise_giris_tarihi  DATE NOT NULL
);
