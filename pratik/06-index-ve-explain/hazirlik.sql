-- Modül 6 için hazırlık: büyük bir ziyaret kaydı tablosu
--
-- Index'lerin etkisini görmek için birkaç bin satır yetmiyor, bu yüzden bu modülde
-- 500.000 satırlık ayrı bir tablo kullanıyoruz. Sitedeki sayfa ziyaretlerini tutuyor.
-- Veri yine deterministik, herkeste aynı.
--
-- Çalıştırmak için (Docker kullanıyorsan):
--   docker compose exec -T db psql -U ogrenci -d eticaret < pratik/06-index-ve-explain/hazirlik.sql
-- Kendi PostgreSQL'inde:
--   psql -d eticaret -f pratik/06-index-ve-explain/hazirlik.sql
--
-- Tabloyu silip yeniden oluşturuyor, yani istediğin kadar çalıştırabilirsin.
-- Denediğin index'leri temizlemek için de en kolay yol bunu tekrar çalıştırmak.

SET client_min_messages = warning;

DROP TABLE IF EXISTS ziyaretler;

CREATE TABLE ziyaretler (
    ziyaret_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    musteri_id      INTEGER REFERENCES musteriler (musteri_id),  -- NULL: giriş yapmadan gezen ziyaretçi
    sayfa           TEXT NOT NULL,
    ziyaret_zamani  TIMESTAMP NOT NULL,
    sure_saniye     INTEGER NOT NULL
);

-- Ziyaretlerin %20'si giriş yapmamış kullanıcılardan.
-- Sayfaların %40'ı anasayfa, %30'u ürün sayfası.
-- Ziyaretler 2024 yılı boyunca yaklaşık 63 saniyede bir geliyor.
INSERT INTO ziyaretler (musteri_id, sayfa, ziyaret_zamani, sure_saniye)
SELECT
    CASE WHEN i % 5 = 0 THEN NULL ELSE 1 + (i::bigint * 7919) % 200 END,
    (ARRAY['anasayfa', 'anasayfa', 'anasayfa', 'anasayfa', 'urun',
           'urun', 'urun', 'sepet', 'odeme', 'arama'])[1 + (i::bigint * 48271 % 2147483647) % 10],
    TIMESTAMP '2024-01-01 00:00:00' + (i * 63) * INTERVAL '1 second',
    5 + (i * 13) % 600
FROM generate_series(1, 500000) AS i;

ANALYZE ziyaretler;
